// Regenerates every golden under testdata/golden/ by running the pinned Seerr
// routes over the fixtures in testdata/tmdb/, together with the derived
// fixtures and the fixture index. No TMDB call is made: a request without a
// fixture fails the run.
//
//   node generate.mjs            write the outputs
//   node generate.mjs --check    write nothing; exit 1 if any output on disk
//                                differs from what the run produces
//   --upstream <dir>             reuse a checkout of the pinned commit (also
//                                GOLDENS_UPSTREAM_DIR); otherwise it is fetched
//                                into a temporary directory
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { parseArgs } from 'node:util';
import { CASES } from './cases.mjs';
import { FIXTURES } from './fixtures.mjs';
import { normalizeForGolden, serializeJson } from './lib/golden.mjs';
import {
  GOLDEN_DIR,
  INDEX_FILE,
  REPO_ROOT,
  TMDB_DIR,
  fixtureFile,
  goldenFile,
  loadAllFixtures,
  openUpstreamRunner,
  validateRegistry,
} from './lib/store.mjs';

const listJsonFiles = (dir) => {
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir, { recursive: true })
    .filter((name) => name.endsWith('.json'))
    .map((name) => join(dir, name));
};

const buildIndex = () => {
  const usage = new Map(FIXTURES.map((fixture) => [fixture.id, { families: new Set(), cases: [] }]));
  for (const entry of CASES) {
    for (const id of entry.fixtures) {
      usage.get(id).families.add(entry.family);
      usage.get(id).cases.push(entry.name);
    }
  }
  return {
    description:
      'Every TMDB fixture, the route families and cases that use it, and whether it was recorded from TMDB or derived from recorded fixtures. Generated by web/tools/goldens/generate.mjs.',
    fixtures: FIXTURES.map((fixture) => ({
      id: fixture.id,
      file: relative(REPO_ROOT, fixtureFile(fixture.id)),
      category: fixture.category,
      source: fixture.derive ? 'derived' : 'recorded',
      ...(fixture.derive
        ? { derivedFrom: [fixture.derive.from, ...(fixture.derive.with ?? [])] }
        : {}),
      routeFamilies: [...usage.get(fixture.id).families].sort(),
      cases: usage.get(fixture.id).cases,
    })),
  };
};

const runCase = async (run, entry, fixturesById) => {
  const fixtures = entry.fixtures.map((id) => fixturesById.get(id));
  const outcome = await run(entry.url, fixtures);
  const problems = [];
  for (const request of outcome.unmatched) {
    problems.push(`case ${entry.name}: no fixture for TMDB request ${JSON.stringify(request)}`);
  }
  for (const id of entry.fixtures) {
    if (!outcome.served.includes(id)) {
      problems.push(`case ${entry.name}: fixture ${id} was never requested`);
    }
  }
  const golden = {
    case: entry.name,
    family: entry.family,
    request: `GET ${entry.url}`,
    fixtures: entry.fixtures,
    status: outcome.status,
    body: normalizeForGolden(outcome.body),
  };
  return { golden, problems };
};

// Every file the run owns, keyed by path, with the content it must have.
const produceOutputs = async (run) => {
  const fixturesById = loadAllFixtures();
  const outputs = new Map();
  for (const fixture of FIXTURES.filter((entry) => entry.derive)) {
    outputs.set(fixtureFile(fixture.id), serializeJson(fixturesById.get(fixture.id)));
  }
  outputs.set(INDEX_FILE, serializeJson(buildIndex()));
  const problems = [];
  for (const entry of CASES) {
    const result = await runCase(run, entry, fixturesById);
    problems.push(...result.problems);
    outputs.set(goldenFile(entry), serializeJson(result.golden));
  }
  return { outputs, problems };
};

const strayFiles = (outputs) => {
  const recordedFiles = new Set(
    FIXTURES.filter((fixture) => !fixture.derive).map((fixture) => fixtureFile(fixture.id))
  );
  return [...listJsonFiles(GOLDEN_DIR), ...listJsonFiles(TMDB_DIR)].filter(
    (file) => !outputs.has(file) && !recordedFiles.has(file)
  );
};

const checkOutputs = (outputs) => {
  const differences = [];
  for (const [file, content] of outputs) {
    const name = relative(REPO_ROOT, file);
    if (!existsSync(file)) {
      differences.push(`${name}: missing`);
    } else if (readFileSync(file, 'utf8') !== content) {
      differences.push(`${name}: differs from the regenerated output`);
    }
  }
  for (const file of strayFiles(outputs)) {
    differences.push(`${relative(REPO_ROOT, file)}: not produced by any fixture or case`);
  }
  return differences;
};

const writeOutputs = (outputs) => {
  for (const [file, content] of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  for (const file of strayFiles(outputs)) {
    if (file.startsWith(GOLDEN_DIR)) {
      rmSync(file);
    } else {
      console.error(`stray fixture left in place: ${relative(REPO_ROOT, file)}`);
    }
  }
};

const main = async () => {
  const { values } = parseArgs({
    options: { check: { type: 'boolean', default: false }, upstream: { type: 'string' } },
  });
  const registryProblems = validateRegistry();
  if (registryProblems.length > 0) {
    throw new Error(registryProblems.join('\n'));
  }
  const runner = await openUpstreamRunner(values.upstream);
  let produced;
  try {
    produced = await produceOutputs(runner.run);
  } finally {
    runner.close();
  }
  if (produced.problems.length > 0) {
    throw new Error(produced.problems.join('\n'));
  }
  if (!values.check) {
    writeOutputs(produced.outputs);
    console.log(`goldens: wrote ${CASES.length} goldens`);
    return;
  }
  const differences = checkOutputs(produced.outputs);
  if (differences.length > 0) {
    console.error(differences.join('\n'));
    console.error('goldens: committed outputs differ; run: node web/tools/goldens/generate.mjs');
    process.exit(1);
  }
  console.log(`goldens: ${CASES.length} goldens reproduce`);
};

main().catch((e) => {
  console.error(`generate.mjs: ${e.message}`);
  process.exit(1);
});
